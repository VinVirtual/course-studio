const kebab = (name) => name.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);
const vars = (tokens) => Object.entries(tokens).map(([name, value]) => `  --${kebab(name)}: ${value};`).join('\n');

export const MIN_CONTRAST = 4.5;
const BACKGROUNDS = ['bg', 'surface', 'sunk'];

const mixHex = (a, b, t) =>
  `#${[1, 3, 5].map((at) => Math.round(parseInt(a.slice(at, at + 2), 16) * (1 - t) + parseInt(b.slice(at, at + 2), 16) * t).toString(16).padStart(2, '0')).join('')}`;

/** The lowest contrast of a colour against a theme's three backgrounds. */
export const worstContrast = (color, tokens) => Math.min(...BACKGROUNDS.map((name) => contrast(color, tokens[name])));

/** Text on an accent-coloured button: white or near-black, whichever reads better. */
export const inkOn = (accent) => (contrast('#ffffff', accent) >= contrast('#111111', accent) ? '#ffffff' : '#111111');

/**
 * The dark-theme version of a course's own accent: mixed toward white (or black) just enough to reach
 * 4.5:1 on the dark backgrounds.
 */
export function darkAccent(accent, dark = PRESETS.paper.dark) {
  for (let step = 0; step <= 100; step += 2) {
    const candidate = mixHex(accent, '#ffffff', step / 100);
    if (worstContrast(candidate, dark) >= MIN_CONTRAST) return candidate;
  }
  return '#ffffff';
}

/** The colour tokens of a theme, light and dark, with a course accent applied. */
export function themeTokens(theme = {}) {
  const preset = PRESETS[theme.preset] ?? PRESETS.paper;
  if (!/^#[0-9a-f]{6}$/i.test(theme.accent ?? '')) return { light: preset.light, dark: preset.dark };
  const accent = theme.accent.toLowerCase();
  const dark = darkAccent(accent, preset.dark);
  return { light: { ...preset.light, accent, accentInk: inkOn(accent) }, dark: { ...preset.dark, accent: dark, accentInk: inkOn(dark) } };
}

export function themeCss(theme = {}) {
  const { light, dark } = themeTokens(theme);
  return `/* generated by course-studio from course.json "theme" */
:root {
${vars(light)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(dark)}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${vars(dark)}
  color-scheme: dark;
}
`;
}

/** WCAG relative luminance of a #rrggbb colour. */
export function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((at) => parseInt(hex.slice(at, at + 2), 16) / 255).map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG contrast ratio between two #rrggbb colours (1 to 21). */
export function contrast(a, b) {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
}
